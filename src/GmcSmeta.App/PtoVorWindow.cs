using System.Windows;
using System.Windows.Controls;
using GmcSmeta.Core.Domain;

namespace GmcSmeta.App;

/// <summary>Explicit column map, preview and user confirmation for third-party VOR XLSX.</summary>
public sealed class PtoVorWindow : Window
{
    private readonly string _path;
    private readonly ComboBox _sheets=new(){Margin=new Thickness(0,2,9,0),MinWidth=130};
    private readonly TextBox _first=new(){Text="2",Width=65,Margin=new Thickness(0,2,8,0)};
    private readonly TextBox _name=new(){Text="2",Width=65,Margin=new Thickness(0,2,8,0)};
    private readonly TextBox _qty=new(){Text="4",Width=65,Margin=new Thickness(0,2,8,0)};
    private readonly TextBox _unit=new(){Text="3",Width=65,Margin=new Thickness(0,2,8,0)};
    private readonly TextBox _system=new(){Text="",Width=65,Margin=new Thickness(0,2,8,0)};
    private readonly DataGrid _preview=new(){AutoGenerateColumns=true,IsReadOnly=true,MinRowHeight=24,CanUserAddRows=false,CanUserDeleteRows=false};
    private readonly CheckBox _confirmed=new(){Content="Я проверил соответствие колонок и строки начала",
        Margin=new Thickness(0,9,0,5)};
    private readonly TextBlock _warnings=new(){TextWrapping=TextWrapping.Wrap,Foreground=
        System.Windows.Media.Brushes.DarkOrange,Margin=new Thickness(0,6,0,5)};
    public PtoVor.Result? Parsed {get;private set;}
    public PtoVorWindow(string path)
    {
        _path=path;
        Title="Импорт ВОР из Excel · явное сопоставление";
        Width=930;Height=690;MinWidth=670;MinHeight=460;
        FontFamily=new System.Windows.Media.FontFamily("Segoe UI");
        WindowStartupLocation=WindowStartupLocation.CenterOwner;
        WorkspaceWindowUi.ApplyChrome(this);
        _preview.SetResourceReference(FrameworkElement.StyleProperty, "DocumentTable");
        _preview.AutoGeneratingColumn += (_, e) =>
        {
            if (e.Column is not DataGridTextColumn column) return;
            bool center = e.PropertyName is "Qty" or "Unit";
            column.ElementStyle = (Style)Application.Current.FindResource(center ? "CompactCostCenter" : "CompactCostText");
            column.HeaderStyle = (Style)Application.Current.FindResource(center ? "KsQuantityHeader" : "KsTextHeader");
            if (e.PropertyName == "Name")
            {
                column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                column.MinWidth = 190;
            }
        };
        TableColumnMenu.SetProtect(_preview, "Name|Qty|Unit");
        TableColumnMenu.EnableAutoGenerated(_preview, "pto-vor-preview");
        var dock=new DockPanel{Margin=new Thickness(14)};
        var controls=new StackPanel();DockPanel.SetDock(controls,Dock.Top);dock.Children.Add(controls);
        controls.Children.Add(new TextBlock{Text="Файл: "+System.IO.Path.GetFileName(path),
            Margin=new Thickness(0,0,0,7)});
        var grid=new WrapPanel{Margin=new Thickness(0,0,0,8)};
        controls.Children.Add(grid);
        void Add(string title,Control field)
        {
            var s=new StackPanel{Margin=new Thickness(0,0,14,3)};
            s.Children.Add(new TextBlock{Text=title});
            s.Children.Add(field);grid.Children.Add(s);
        }
        Add("Лист",_sheets);Add("Первая строка",_first);Add("Имя (номер)",_name);
        Add("Объём (номер)",_qty);Add("Ед. (0/пусто)",_unit);Add("Система (0/пусто)",_system);
        var actions=new WrapPanel{Margin=new Thickness(0,0,0,8)};
        controls.Children.Add(actions);
        var parse=new Button{Content="Просмотр строк",Padding=new Thickness(12,7,12,7),
            Margin=new Thickness(0,0,8,0)};
        parse.SetResourceReference(FrameworkElement.StyleProperty, "PythonToolbarButton");
        parse.SetResourceReference(ContentControl.ContentTemplateProperty, "IconLabelSearch");
        parse.Click+=(_,_)=>Parse();actions.Children.Add(parse);
        controls.Children.Add(_warnings);
        var bottom=new StackPanel();DockPanel.SetDock(bottom,Dock.Bottom);dock.Children.Add(bottom);
        bottom.Children.Add(_confirmed);
        var accept=new Button{Content="Перенести проверенные строки",HorizontalAlignment=HorizontalAlignment.Right,
            Padding=new Thickness(12,8,12,8)};
        accept.SetResourceReference(FrameworkElement.StyleProperty, "PythonToolbarPrimary");
        accept.SetResourceReference(ContentControl.ContentTemplateProperty, "IconLabelCheck");
        accept.Click+=(_,_)=>
        {
            if(Parsed is null||_confirmed.IsChecked!=true)
            {
                MessageBox.Show(this,"Сначала просмотрите строки и подтвердите сопоставление.","ВОР");
                return;
            }
            DialogResult=true;
        };
        bottom.Children.Add(accept);
        dock.Children.Add(_preview);
        Content=dock;
        _sheets.ItemsSource=PtoVor.Sheets(path);
        _sheets.SelectedIndex=0;
        foreach(var edit in new[]{_first,_name,_qty,_unit,_system})
            edit.TextChanged+=(_,_)=>Invalid();
        _sheets.SelectionChanged+=(_,_)=>Invalid();
    }
    private void Invalid()
    {
        Parsed=null;_confirmed.IsChecked=false;
        _preview.ItemsSource=null;
        _warnings.Text="Проверьте сопоставление и нажмите «Просмотр строк».";
    }
    private int Column(TextBox box,string label)
    {
        var raw=box.Text.Trim();
        if(raw.Length==0)return 0;
        if(!int.TryParse(raw,out var result)||result<0||result>500)
            throw new ArgumentException("Неверный номер колонки «"+label+"».");
        return result;
    }
    private void Parse()
    {
        try
        {
            if(!int.TryParse(_first.Text.Trim(),out var first)||first<1)
                throw new ArgumentException("Первая строка должна быть положительным числом.");
            var cols=new PtoVor.Columns(Column(_name,"Имя"),Column(_qty,"Объём"),
                Column(_unit,"Ед."),Column(_system,"Система"));
            Parsed=PtoVor.Read(_path,_sheets.SelectedItem?.ToString()??"",first,cols);
            _preview.ItemsSource=Parsed.Rows.Take(250).ToArray();
            _warnings.Text="Найдено строк: "+Parsed.Rows.Count+
                ". Предпросмотр первых 250. Предупреждений: "+Parsed.Warnings.Count+"\n"+
                string.Join("\n",Parsed.Warnings.Take(8));
            _confirmed.IsChecked=false;
        }
        catch(Exception ex)
        {
            Invalid();
            MessageBox.Show(this,ex.Message,"Проверка ВОР",MessageBoxButton.OK,MessageBoxImage.Warning);
        }
    }
}
