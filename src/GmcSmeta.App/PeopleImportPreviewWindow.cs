using System.IO;
using System.Windows;
using System.Windows.Controls;
using GmcSmeta.Core.Domain;

namespace GmcSmeta.App;

/// <summary>
/// Actual Excel import preview and optional 1-based column mapping. No SQL writes occur
/// until the user explicitly confirms this dialog and the caller starts its transaction.
/// </summary>
public sealed class PeopleImportPreviewWindow : Window
{
    private readonly string _file;
    private readonly TextBox _fio = new() { Width = 60 };
    private readonly TextBox _post = new() { Width = 60 };
    private readonly TextBox _birth = new() { Width = 60 };
    private readonly TextBox _model = new() { Width = 60 };
    private readonly TextBox _plate = new() { Width = 60 };
    private readonly DataGrid _people = NewGrid();
    private readonly DataGrid _cars = NewGrid();
    private readonly TextBlock _summary = new()
    {
        Foreground = System.Windows.Media.Brushes.DimGray, TextWrapping = TextWrapping.Wrap
    };
    public PeopleImportPreview Preview { get; private set; }

    private static DataGrid NewGrid()
    {
        var grid = new DataGrid
        {
        AutoGenerateColumns = true,
        IsReadOnly = true,
        CanUserAddRows = false,
        HeadersVisibility = DataGridHeadersVisibility.Column,
        MinRowHeight = 27,
        Margin = new Thickness(0, 6, 0, 0),
        GridLinesVisibility = DataGridGridLinesVisibility.Horizontal
        };
        WorkspaceWindowUi.StyleTable(grid);
        grid.AutoGeneratingColumn += (_, e) =>
        {
            if (e.Column is DataGridTextColumn col)
                WorkspaceWindowUi.StyleColumn(col, e.PropertyName.Contains("Date", StringComparison.OrdinalIgnoreCase) ||
                    e.PropertyName.Contains("Birth", StringComparison.OrdinalIgnoreCase) ||
                    e.PropertyName.Contains("Plate", StringComparison.OrdinalIgnoreCase) ? TextAlignment.Center : TextAlignment.Left);
        };
        return grid;
    }

    public PeopleImportPreviewWindow(string file, PeopleImportPreview preview)
    {
        _file = file;
        Preview = preview;
        TableColumnMenu.SetProtect(_people, "Fio|Birth");
        TableColumnMenu.EnableAutoGenerated(_people, "people-import-preview");
        TableColumnMenu.SetProtect(_cars, "Model|Plate");
        TableColumnMenu.EnableAutoGenerated(_cars, "cars-import-preview");
        Title = "Предпросмотр загрузки из Excel";
        Width = 970;
        Height = 690;
        MinWidth = 760;
        MinHeight = 540;
        WorkspaceWindowUi.ApplyChrome(this);
        WindowStartupLocation = WindowStartupLocation.CenterOwner;
        Background = System.Windows.Media.Brushes.White;

        var root = new DockPanel { Margin = new Thickness(20) };
        var head = new StackPanel { Margin = new Thickness(0, 0, 0, 12) };
        head.Children.Add(WorkspaceWindowUi.Heading("Предпросмотр и сопоставление колонок"));
        head.Children.Add(new TextBlock
        {
            Text = "Укажите номера колонок Excel (A = 1, B = 2). Пустые поля означают автоматическое распознавание. " +
                   "Ни один сотрудник не будет изменён до нажатия «Импортировать».",
            TextWrapping = TextWrapping.Wrap,
            Margin = new Thickness(0, 4, 0, 8),
            Foreground = System.Windows.Media.Brushes.DimGray
        });
        var mapping = new WrapPanel();
        mapping.Children.Add(Labeled("ФИО", _fio));
        mapping.Children.Add(Labeled("Должность", _post));
        mapping.Children.Add(Labeled("Дата рождения", _birth));
        mapping.Children.Add(Labeled("Марка/модель", _model));
        mapping.Children.Add(Labeled("Госномер", _plate));
        var apply = new Button { Content = "Перечитать с указанными колонками",
            Padding = new Thickness(10, 6, 10, 6), Margin = new Thickness(8, 6, 0, 0),
            VerticalAlignment = VerticalAlignment.Bottom };
        WorkspaceWindowUi.StyleButton(apply, icon: "IconLabelRefresh");
        apply.Click += (_, _) => ReloadMapping();
        mapping.Children.Add(apply);
        head.Children.Add(mapping);
        _summary.Margin = new Thickness(0, 10, 0, 0);
        head.Children.Add(_summary);
        DockPanel.SetDock(head, Dock.Top);
        root.Children.Add(head);

        var footer = new StackPanel { Orientation = Orientation.Horizontal,
            HorizontalAlignment = HorizontalAlignment.Right, Margin = new Thickness(0, 14, 0, 0) };
        var import = new Button { Content = "Импортировать",
            Padding = new Thickness(16, 8, 16, 8), FontWeight = FontWeights.SemiBold,
            Background = new System.Windows.Media.SolidColorBrush(
                System.Windows.Media.Color.FromRgb(249, 115, 22)),
            Foreground = System.Windows.Media.Brushes.White };
        import.Click += (_, _) =>
        {
            if (Preview.People.Count + Preview.Cars.Count == 0)
            {
                MessageBox.Show(this, "В выбранных колонках не обнаружено данных.");
                return;
            }
            DialogResult = true;
            Close();
        };
        var cancel = new Button { Content = "Отмена", Padding = new Thickness(16, 8, 16, 8),
            Margin = new Thickness(8, 0, 0, 0) };
        cancel.Click += (_, _) => { DialogResult = false; Close(); };
        WorkspaceWindowUi.StyleButton(import, primary: true, icon: "IconLabelUpload");
        WorkspaceWindowUi.StyleButton(cancel);
        footer.Children.Add(import);
        footer.Children.Add(cancel);
        DockPanel.SetDock(footer, Dock.Bottom);
        root.Children.Add(footer);

        var tabs = new TabControl();
        tabs.Items.Add(new TabItem { Header = "Сотрудники", Content = _people });
        tabs.Items.Add(new TabItem { Header = "Автомобили", Content = _cars });
        root.Children.Add(tabs);
        Content = root;
        ShowRows();
    }

    private static FrameworkElement Labeled(string caption, TextBox box)
    {
        var container = new StackPanel { Margin = new Thickness(0, 0, 12, 0) };
        var label = new TextBlock { Text = caption, Margin = new Thickness(0, 0, 0, 4) };
        label.SetResourceReference(TextBlock.FontSizeProperty, "UiCaptionSize");
        container.Children.Add(label);
        container.Children.Add(box);
        return container;
    }

    private static int? Column(TextBox textBox)
    {
        var text = textBox.Text.Trim();
        if (text.Length == 0) return null;
        if (int.TryParse(text, out var column) && column is >= 1 and <= 30)
            return column;
        throw new ArgumentException("Номер колонки должен быть целым числом от 1 до 30.");
    }

    private void ReloadMapping()
    {
        try
        {
            if (!File.Exists(_file)) throw new FileNotFoundException("Исходный Excel-файл не найден.");
            var next = PeopleDocuments.ReadImport(_file, Column(_fio), Column(_post),
                Column(_birth), Column(_model), Column(_plate));
            Preview = next;
            ShowRows();
        }
        catch (Exception ex)
        {
            MessageBox.Show(this, ex.Message, "Предпросмотр импорта",
                MessageBoxButton.OK, MessageBoxImage.Warning);
        }
    }

    private void ShowRows()
    {
        _people.ItemsSource = Preview.People.Take(500).ToArray();
        _cars.ItemsSource = Preview.Cars.Take(500).ToArray();
        _summary.Text = $"Обнаружено: {Preview.People.Count} сотрудников и {Preview.Cars.Count} автомобилей." +
            (Preview.People.Count > 500 || Preview.Cars.Count > 500
                ? " В таблице показаны первые 500; импорт будет полным." : "") +
            " Дубликаты проверяются на сервере; существующие непустые поля не перезаписываются.";
    }
}
