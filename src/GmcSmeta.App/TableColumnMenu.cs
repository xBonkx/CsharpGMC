namespace GmcSmeta.App;

/// <summary>Local column layout, shared by opt-in tables. Never edits rows or SQL.
/// Mode-controlled columns are excluded explicitly; no row menu is replaced.</summary>
public static class TableColumnMenu
{
    public static readonly DependencyProperty KeyProperty = DependencyProperty.RegisterAttached(
        "Key", typeof(string), typeof(TableColumnMenu), new PropertyMetadata("", KeyChanged));
    public static void SetKey(DependencyObject target, string value) => target.SetValue(KeyProperty, value);
    public static string GetKey(DependencyObject target) => (string)target.GetValue(KeyProperty);

    public static readonly DependencyProperty ExcludeProperty = DependencyProperty.RegisterAttached(
        "Exclude", typeof(string), typeof(TableColumnMenu), new PropertyMetadata(""));
    public static void SetExclude(DependencyObject target, string value) => target.SetValue(ExcludeProperty, value);
    public static string GetExclude(DependencyObject target) => (string)target.GetValue(ExcludeProperty);

    public static readonly DependencyProperty ProtectProperty = DependencyProperty.RegisterAttached(
        "Protect", typeof(string), typeof(TableColumnMenu), new PropertyMetadata("Наименование"));
    public static void SetProtect(DependencyObject target, string value) => target.SetValue(ProtectProperty, value);
    public static string GetProtect(DependencyObject target) => (string)target.GetValue(ProtectProperty);

    public static readonly DependencyProperty StableIdProperty = DependencyProperty.RegisterAttached(
        "StableId", typeof(string), typeof(TableColumnMenu), new PropertyMetadata(""));
    public static void SetStableId(DependencyObject target, string value) => target.SetValue(StableIdProperty, value);
    public static string GetStableId(DependencyObject target) => (string)target.GetValue(StableIdProperty);

    public static readonly DependencyProperty MenuTitleProperty = DependencyProperty.RegisterAttached(
        "MenuTitle", typeof(string), typeof(TableColumnMenu), new PropertyMetadata(""));
    public static void SetMenuTitle(DependencyObject target, string value) => target.SetValue(MenuTitleProperty, value);
    public static string GetMenuTitle(DependencyObject target) => (string)target.GetValue(MenuTitleProperty);

    private static readonly System.Runtime.CompilerServices.ConditionalWeakTable<DataGrid, Layout> Layouts = new();

    internal static void RefreshDynamic(DataGrid grid, string key, bool ownHeaderMenu)
    {
        if (!ValidKey(key)) throw new ArgumentException("Invalid column layout key.", nameof(key));
        if (!Layouts.TryGetValue(grid, out var layout))
            layout = Attach(grid, key, ownHeaderMenu);
        layout.Rebuild(key);
    }

    internal static void EnableAutoGenerated(DataGrid grid, string key)
    {
        // Auto-generated columns are replaced when ItemsSource changes. Capture
        // the complete collection after WPF finishes generation, not each column.
        grid.AutoGeneratedColumns += (_, _) =>
            grid.Dispatcher.BeginInvoke(DispatcherPriority.Loaded, new Action(() =>
            {
                if (grid.Columns.Count > 0) RefreshDynamic(grid, key, ownHeaderMenu: true);
            }));
    }

    internal static void AppendDynamicMenu(DataGrid grid, ItemsControl menu)
    {
        if (!Layouts.TryGetValue(grid, out var layout)) return;
        var columns = new MenuItem { Header = "Столбцы" };
        if (!layout.Populate(columns)) return;
        if (menu.Items.Count != 0) menu.Items.Add(new Separator());
        menu.Items.Add(columns);
    }

    private static bool ValidKey(string key) => !string.IsNullOrWhiteSpace(key) &&
        key.All(ch => char.IsAsciiLetterOrDigit(ch) || ch == '-' || ch == '_');

    private static void KeyChanged(DependencyObject target, DependencyPropertyChangedEventArgs e)
    {
        if (target is not DataGrid grid || e.NewValue is not string key || !ValidKey(key)) return;
        if (Layouts.TryGetValue(grid, out var existing))
        {
            existing.Rebuild(key);
            return;
        }
        var layout = Attach(grid, key, ownHeaderMenu: true);
        if (grid.IsLoaded) layout.Initialize();
    }

    private static Layout Attach(DataGrid grid, string key, bool ownHeaderMenu)
    {
        var layout = new Layout(grid, key);
        Layouts.Add(grid, layout);
        grid.Loaded += (_, _) => layout.Initialize();
        if (ownHeaderMenu) InstallHeaderMenu(grid, anchor => layout.Show(anchor));
        grid.ColumnReordered += (_, _) => layout.SaveOrder();
        grid.AddHandler(Thumb.DragStartedEvent, new DragStartedEventHandler(layout.ResizeStarted), true);
        grid.AddHandler(Thumb.DragCompletedEvent, new DragCompletedEventHandler(layout.ResizeCompleted), true);
        grid.PreviewMouseLeftButtonDown += layout.HeaderDoubleClick;
        return layout;
    }

    // Preview route distinguishes real column headers (including their resize
    // grippers) from cells, row headers, scrollbars and background. Handle the
    // input before ContextMenuService opens the grid's existing row menu.
    internal static void InstallHeaderMenu(DataGrid grid, Action<FrameworkElement> open)
    {
        // Use the tunneling mouse event rather than the re-raised direct
        // right-button event; hit-test the actual point rather than selection.
        grid.AddHandler(Mouse.PreviewMouseUpEvent, new MouseButtonEventHandler((_, e) =>
        {
            if (e.ChangedButton != MouseButton.Right) return;
            var header = HeaderFrom(grid.InputHitTest(e.GetPosition(grid)) as DependencyObject, grid);
            if (header is null) return;
            e.Handled = true;
            if (CanChange(grid)) open(grid);
            else
            {
                var notice = new ContextMenu { PlacementTarget = grid, Placement = PlacementMode.MousePoint };
                notice.Items.Add(new MenuItem { Header = "Завершите редактирование, чтобы настроить столбцы", IsEnabled = false });
                notice.IsOpen = true;
            }
        }), true);
    }

    private static DataGridColumnHeader? HeaderFrom(DependencyObject? node, DataGrid grid)
    {
        DataGridColumnHeader? header = null;
        for (; node is not null; node = node is Visual || node is Visual3D
                 ? VisualTreeHelper.GetParent(node) : LogicalTreeHelper.GetParent(node))
        {
            if (node is DataGridColumnHeader h) header = h;
            if (node is DataGrid owner) return owner == grid ? header : null;
        }
        return null;
    }

    private static bool CanChange(DataGrid grid) =>
        CollectionViewSource.GetDefaultView(grid.ItemsSource ?? grid.Items) is not
            IEditableCollectionView { IsEditingItem: true } and not IEditableCollectionView { IsAddingNew: true };

    internal static string Title(DataGridColumn column)
    {
        var explicitTitle = GetMenuTitle(column);
        if (!string.IsNullOrWhiteSpace(explicitTitle)) return explicitTitle;
        static IEnumerable<string> Parts(object? value)
        {
            if (value is TextBlock text) yield return text.Text;
            else if (value is Panel panel)
            {
                foreach (UIElement child in panel.Children)
                    foreach (var part in Parts(child)) yield return part;
            }
            else if (value is ContentControl control)
            {
                foreach (var part in Parts(control.Content)) yield return part;
            }
            else if (value is string str) yield return str;
        }
        var title = string.Join(" · ", Parts(column.Header).Where(s => !string.IsNullOrWhiteSpace(s)));
        return string.IsNullOrWhiteSpace(title) ? "Столбец " + (column.DisplayIndex + 1) :
            string.Join(" ", title.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
    }

    private sealed class Preferences
    {
        public Preferences() { }
        public List<string> Hidden { get; set; } = new();
        public Dictionary<string, double> Widths { get; set; } = new();
        public List<string> Order { get; set; } = new();
    }

    private sealed record Entry(DataGridColumn Column, string Id, string Title, DataGridLength Width,
        int Index, bool Protected, bool Excluded, bool FixedOrder);

    private sealed class Layout(DataGrid grid, string key)
    {
        private Entry[] _entries = Array.Empty<Entry>();

        internal void Rebuild(string newKey)
        {
            // Some ItemsSource changes reuse the same columns. Do not recapture
            // user-hidden columns as mode-controlled defaults.
            if (key == newKey && SameColumns()) return;
            if (key != newKey && SameColumns())
            {
                // A reused grid must not carry the previous view's user-hidden
                // columns, sizes or order into the new layout key. Keep columns
                // hidden by the view itself (Excluded) untouched.
                _applying = true;
                try
                {
                    foreach (var entry in _entries.Where(x => !x.Excluded))
                    {
                        if (!entry.Protected && _prefs.Hidden.Contains(entry.Id))
                            entry.Column.Visibility = Visibility.Visible;
                        entry.Column.Width = entry.Width;
                    }
                    if (grid.CanUserReorderColumns)
                        ApplyOrder(Array.Empty<string>());
                }
                finally { _applying = false; }
            }
            _initialized = false;
            _resizeStart = null;
            _entries = Array.Empty<Entry>();
            key = newKey;
            Initialize();
        }
        private bool _initialized, _applying;
        private Preferences _prefs = new();
        private Dictionary<DataGridColumn, DataGridLength>? _resizeStart;
        private string PathName => Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            "GMC-Smeta-Next", "column-layouts", key + ".json");

        private Preferences Read()
        {
            try
            {
                if (!File.Exists(PathName)) return new();
                var value = JsonSerializer.Deserialize<Preferences>(File.ReadAllText(PathName)) ?? new();
                value.Hidden ??= new();
                value.Widths ??= new();
                value.Order ??= new();
                return value;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or JsonException or NotSupportedException)
            { return new(); }
        }

        private void Save(Action<Preferences> change)
        {
            string? temporary = null;
            try
            {
                // Another window may already have saved this same table key.
                // Merge only the field changed by the current action.
                var latest = Read();
                change(latest);
                Directory.CreateDirectory(Path.GetDirectoryName(PathName)!);
                temporary = PathName + "." + Guid.NewGuid().ToString("N") + ".tmp";
                File.WriteAllText(temporary, JsonSerializer.Serialize(latest));
                File.Move(temporary, PathName, overwrite: true);
                _prefs = latest;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
            finally
            {
                try { if (temporary is not null && File.Exists(temporary)) File.Delete(temporary); }
                catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
            }
        }

        private static HashSet<string> Names(string value) =>
            value.Split('|', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .ToHashSet(StringComparer.Ordinal);

        internal void Initialize()
        {
            if (_initialized || grid.Columns.Count == 0) return;
            var exclude = Names(GetExclude(grid));
            var protect = Names(GetProtect(grid));
            var columns = grid.Columns.OrderBy(c => c.DisplayIndex).ToArray();
            string Identity(DataGridColumn column)
            {
                var stable = GetStableId(column);
                if (!string.IsNullOrWhiteSpace(stable)) return stable;
                return !string.IsNullOrWhiteSpace(column.SortMemberPath) ? column.SortMemberPath :
                    column is DataGridBoundColumn { Binding: Binding binding } && !string.IsNullOrWhiteSpace(binding.Path?.Path)
                        ? binding.Path.Path : Title(column);
            }
            _entries = columns.Select((column, index) =>
            {
                var title = Title(column);
                var identity = Identity(column);
                var id = identity + "#" + columns.Take(index).Count(c => Identity(c) == identity);
                var excluded = exclude.Contains(title) ||
                    (column.Visibility != Visibility.Visible && !protect.Contains(title));
                return new Entry(column, id, title, column.Width, index,
                    index == 0 || protect.Contains(title), excluded,
                    index == 0 || index < grid.FrozenColumnCount || excluded || !column.CanUserReorder);
            }).ToArray();
            _initialized = true;
            _prefs = Read();
            _applying = true;
            try
            {
                foreach (var entry in _entries.Where(x => !x.Excluded))
                {
                    if (!entry.Protected && _prefs.Hidden.Contains(entry.Id) && CanHide(entry.Column))
                        entry.Column.Visibility = Visibility.Collapsed;
                    if (_prefs.Widths.TryGetValue(entry.Id, out var width) &&
                        double.IsFinite(width) && width is >= 36 and <= 2000)
                        entry.Column.Width = new DataGridLength(Math.Clamp(width, entry.Column.MinWidth,
                            Math.Max(entry.Column.MinWidth, entry.Column.MaxWidth)));
                }
                if (grid.CanUserReorderColumns)
                {
                    foreach (var entry in _entries.Where(x => x.FixedOrder))
                        entry.Column.CanUserReorder = false;
                    ApplyOrder(_prefs.Order);
                }
            }
            finally { _applying = false; }
        }

        private bool CanHide(DataGridColumn column) => column.Visibility != Visibility.Visible ||
            grid.Columns.Count(c => c.Visibility == Visibility.Visible) > 1;

        private void ApplyOrder(IEnumerable<string> preferred)
        {
            var defaults = _entries.Select(x => x.Id).ToArray();
            var fixedIds = _entries.Where(x => x.FixedOrder).Select(x => x.Id).ToHashSet();
            var byId = _entries.ToDictionary(x => x.Id, x => x.Column);
            var ordered = ColumnOrderPolicy.Normalize(defaults, preferred, fixedIds);
            for (int i = 0; i < ordered.Length; i++)
                if (byId[ordered[i]].DisplayIndex != i) byId[ordered[i]].DisplayIndex = i;
        }

        private bool SameColumns() => _initialized && grid.Columns.Count == _entries.Length &&
            _entries.All(x => grid.Columns.Contains(x.Column));

        private bool Ready() => !_applying && CanChange(grid) && SameColumns();

        internal void Show(FrameworkElement anchor)
        {
            Initialize();
            if (!Ready()) return;
            // Keep the popup anchored to the grid even if the clicked header is hidden.
            var menu = new ContextMenu { PlacementTarget = grid, Placement = PlacementMode.MousePoint };
            if (Populate(menu)) menu.IsOpen = true;
        }

        internal bool Populate(ItemsControl menu)
        {
            if (!Ready()) return false;
            var snapshot = _entries;
            bool Current() => ReferenceEquals(snapshot, _entries) && Ready();
            menu.Items.Add(new MenuItem { Header = "Показывать столбцы", IsEnabled = false });
            var items = new List<(Entry Entry, MenuItem Item)>();
            foreach (var entry in _entries.Where(x => !x.Excluded).OrderBy(x => x.Column.DisplayIndex))
            {
                var item = new MenuItem
                {
                    Header = Title(entry.Column), IsCheckable = true,
                    IsChecked = entry.Column.Visibility == Visibility.Visible,
                    IsEnabled = !entry.Protected, StaysOpenOnClick = true,
                    ToolTip = entry.Protected ? "Этот столбец скрыть нельзя" : null
                };
                item.Click += (_, _) =>
                {
                    if (!Current() || !item.IsChecked && !CanHide(entry.Column))
                    { item.IsChecked = entry.Column.Visibility == Visibility.Visible; return; }
                    entry.Column.Visibility = item.IsChecked ? Visibility.Visible : Visibility.Collapsed;
                    SaveVisibility(new[] { entry });
                };
                items.Add((entry, item));
                menu.Items.Add(item);
            }
            menu.Items.Add(new Separator());
            var show = new MenuItem { Header = "Показать все столбцы" };
            show.Click += (_, _) =>
            {
                if (!Current()) return;
                foreach (var (entry, item) in items.Where(x => !x.Entry.Protected))
                { entry.Column.Visibility = Visibility.Visible; item.IsChecked = true; }
                SaveVisibility(items.Where(x => !x.Entry.Protected).Select(x => x.Entry));
            };
            menu.Items.Add(show);
            var widths = new MenuItem { Header = "Вернуть ширину столбцов по умолчанию" };
            widths.Click += (_, _) =>
            {
                if (!Current()) return;
                foreach (var entry in _entries.Where(x => !x.Excluded)) entry.Column.Width = entry.Width;
                Save(prefs => prefs.Widths.Clear());
            };
            menu.Items.Add(widths);
            var order = new MenuItem { Header = "Вернуть порядок столбцов", IsEnabled = grid.CanUserReorderColumns };
            order.Click += (_, _) =>
            {
                if (!Current() || !grid.CanUserReorderColumns) return;
                _applying = true;
                try
                {
                    ApplyOrder(Array.Empty<string>());
                    Save(prefs => prefs.Order.Clear());
                }
                finally { _applying = false; }
            };
            menu.Items.Add(order);
            return true;
        }

        private void SaveVisibility(IEnumerable<Entry> changedEntries)
        {
            var changed = changedEntries.Where(x => !x.Excluded && !x.Protected).ToArray();
            var changedIds = changed.Select(x => x.Id).ToHashSet();
            Save(prefs => prefs.Hidden = prefs.Hidden.Where(id => !changedIds.Contains(id))
                .Concat(changed.Where(x => x.Column.Visibility != Visibility.Visible)
                    .Select(x => x.Id)).Distinct().ToList());
        }

        internal void SaveOrder()
        {
            if (!Ready() || !grid.CanUserReorderColumns) return;
            _applying = true;
            try
            {
                ApplyOrder(_entries.OrderBy(x => x.Column.DisplayIndex).Select(x => x.Id).ToArray());
                var order = _entries.OrderBy(x => x.Column.DisplayIndex).Select(x => x.Id).ToList();
                Save(prefs => prefs.Order = order);
            }
            finally { _applying = false; }
        }

        internal void ResizeStarted(object sender, DragStartedEventArgs e)
        {
            if (!Ready() || HeaderFrom(e.OriginalSource as DependencyObject, grid) is null) return;
            _resizeStart = _entries.Where(x => !x.Excluded).ToDictionary(x => x.Column, x => x.Column.Width);
        }

        internal void ResizeCompleted(object sender, DragCompletedEventArgs e)
        {
            var before = _resizeStart;
            _resizeStart = null;
            if (before is not null && !e.Canceled) SaveWidths(before);
        }

        internal void HeaderDoubleClick(object sender, MouseButtonEventArgs e)
        {
            if (e.ClickCount != 2 || e.OriginalSource is not Thumb thumb || HeaderFrom(thumb, grid) is null || !Ready()) return;
            var before = _entries.Where(x => !x.Excluded).ToDictionary(x => x.Column, x => x.Column.Width);
            grid.Dispatcher.BeginInvoke(DispatcherPriority.Background, new Action(() => SaveWidths(before)));
        }

        private void SaveWidths(Dictionary<DataGridColumn, DataGridLength> before)
        {
            if (!Ready()) return;
            var changed = new Dictionary<string, double>();
            foreach (var entry in _entries.Where(x => !x.Excluded))
            {
                var column = entry.Column;
                if (!before.TryGetValue(column, out var width) || width.Equals(column.Width) ||
                    column.Visibility != Visibility.Visible) continue;
                var actual = column.ActualWidth;
                if (!double.IsFinite(actual) || actual is < 36 or > 2000) continue;
                changed[entry.Id] = actual;
            }
            if (changed.Count > 0)
                Save(prefs =>
                {
                    foreach (var (id, width) in changed) prefs.Widths[id] = width;
                });
        }
    }
}
