#!/usr/bin/env python3
"""Read-only context-menu/command inventory of committed C# and Python trees.

Candidates are heuristic source locations, never proof of a command or parity.
No GUI, SQL, external packages, or network access.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import sys

# Reuse the repository's tested, NUL-safe Git blob reader.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "source-size"))
from source_size import git, read_blobs, EXCLUDED_DIRS, GENERATED_SUFFIXES

RULES = {
    "cs": {
        "menu": r"\b(?:ContextMenu|MenuItem|Menu|Popup|NotifyIcon|ToolStripMenuItem|ContextMenuStrip)\b",
        "route": r"\b(?:ContextMenuOpening|ContextMenuClosing|MouseRightButton(?:Down|Up)|PreviewMouseRightButton(?:Down|Up)|MouseButton\.Right|PlacementTarget|IsOpen)\b",
        "keyboard": r"\b(?:KeyBinding|InputBinding|InputGestureText|PreviewKeyDown|KeyDown|Key\.Apps|Key\.F10|RoutedCommand|RoutedUICommand|CommandBinding)\b",
        "dialog": r"\b(?:ShowDialog|MessageBox\.Show|OpenFileDialog|SaveFileDialog|OpenFolderDialog)\b",
        "editor": r"\b(?:TextBox|RichTextBox|PasswordBox|DataGridTextColumn)\b",
        "factory": r"\b(?:AddMenuItem|CreateMenuItem|BuildMenu|CreateMenu|AddAction|MenuCommand|ContextMenuTarget|TableColumnMenu)\b",
    },
    "xaml": {
        "menu": r"(?:\b(?:ContextMenu|MenuItem|Menu|Popup)\b|\.ContextMenu\b)",
        "route": r"\b(?:ContextMenuOpening|ContextMenuClosing|PreviewMouseRightButton\w*|MouseRightButton\w*|PlacementTarget|IsOpen)\b",
        "keyboard": r"\b(?:KeyBinding|InputBinding|InputGestureText|PreviewKeyDown|KeyDown|CommandBinding|Command)\b",
        "editor": r"\b(?:TextBox|RichTextBox|PasswordBox|DataGridTextColumn)\b",
    },
    "py": {
        "menu": r"\b(?:QMenu|QAction|QActionGroup|QSystemTrayIcon|QWidgetAction|addAction|addMenu|setMenu|menuBar)\b",
        "route": r"\b(?:setContextMenuPolicy|customContextMenuRequested|contextMenuEvent|createStandardContextMenu|CustomContextMenu|RightButton|popup)\b",
        "keyboard": r"\b(?:QShortcut|QKeySequence|setShortcut|keyPressEvent|eventFilter|Key_Menu|Key_F10)\b",
        "dialog": r"\b(?:QDialog|QMessageBox|QFileDialog|exec_|exec)\b",
        "editor": r"\b(?:QLineEdit|QTextEdit|QPlainTextEdit|QAbstractItemView|QStyledItemDelegate)\b",
    },
}
PATTERNS = {suffix: {kind: re.compile(pattern) for kind, pattern in rules.items()}
            for suffix, rules in RULES.items()}
FIELDS = ["candidate_id", "language", "revision", "path", "line", "kinds", "source", "scope", "status"]
REVIEW_FIELDS = ["menu_id", "module", "target", "state", "command_id", "text", "order", "shortcut",
                 "icon", "enabled", "visible", "handler", "dialog", "python_candidate_ids",
                 "csharp_candidate_ids", "classification", "notes"]

def candidates(source, suffix):
    for line, value in enumerate(source.splitlines(), 1):
        kinds = [kind for kind, pattern in PATTERNS[suffix].items() if pattern.search(value)]
        if kinds:
            yield line, kinds, value.strip()

def scope(path):
    parts = PurePosixPath(path).parts
    return "test" if any(p.lower() in {"test", "tests"} for p in parts) or parts[-1].startswith("test_") else "source"

def snapshot(root, revision, languages):
    sha = git(root, "rev-parse", "--verify", revision + "^{commit}").decode("ascii").strip()
    tracked = git(root, "ls-tree", "-r", "-z", sha).split(b"\0")
    selected, excluded = {}, {}
    for entry in tracked:
        if not entry:
            continue
        meta, raw_path = entry.split(b"\t", 1)
        mode, kind, oid = meta.decode("ascii").split()
        path = raw_path.decode("utf-8")
        name = PurePosixPath(path)
        suffix = name.suffix.lower().lstrip(".")
        if suffix not in languages:
            continue
        if mode == "120000" or kind != "blob":
            excluded[path] = "nonregular"
        elif any(part.lower() in EXCLUDED_DIRS for part in name.parts[:-1]) or name.name.lower().endswith(GENERATED_SUFFIXES):
            excluded[path] = "generated/vendor/build"
        else:
            selected[path] = (suffix, oid)
    if not selected:
        raise ValueError(f"No tracked {languages} sources in {root} at {sha}")
    blobs = read_blobs(root, sorted({oid for _, oid in selected.values()}))
    rows = []
    scanned = 0
    files = []
    for path, (suffix, oid) in sorted(selected.items()):
        text = blobs[oid].decode("utf-8-sig")
        if re.search(r"<auto-generated\b", text[:2048], re.I):
            excluded[path] = "auto-generated header"
            continue
        scanned += 1
        language = "python" if suffix == "py" else "csharp"
        first = len(rows)
        for line, kinds, value in candidates(text, suffix):
            key = f"{language}\0{sha}\0{path}\0{line}"
            rows.append(dict(candidate_id=hashlib.sha256(key.encode("utf-8")).hexdigest(),
                             language=language, revision=sha, path=path, line=line,
                             kinds=";".join(kinds), source=value, scope=scope(path), status="REVIEW"))
        files.append(dict(path=path, blob=oid, scope=scope(path), candidate_count=len(rows) - first))
    return dict(revision=sha, scanned_files=scanned, files=files, excluded=excluded, candidates=rows)

def validate_review(review, rows):
    """Check identity and traceability only; do not certify behavioral parity."""
    if not isinstance(review, list):
        raise ValueError("Review must be a JSON array")
    index = {row["candidate_id"]: row for row in rows}
    if len(index) != len(rows):
        raise ValueError("Duplicate inventory candidate identity")
    keys = set()
    for command in review:
        if not isinstance(command, dict) or set(command) != set(REVIEW_FIELDS):
            raise ValueError("Invalid reviewed command fields")
        key = tuple(command[name] for name in ("menu_id", "state", "command_id"))
        if any(not isinstance(value, str) or not value.strip() or value != value.strip() for value in key) or key in keys:
            raise ValueError("Missing or repeated menu/state/command identity")
        keys.add(key)
        classification = command["classification"]
        if classification not in {"MATCH", "EXTENSION", "DEFECT", "N/A"}:
            raise ValueError("Reviewed classification must be explicit")
        if type(command["order"]) is not int or command["order"] < 0:
            raise ValueError("Invalid order")
        for field in ("module", "target", "text", "shortcut", "icon", "enabled", "visible", "handler", "dialog", "notes"):
            if not isinstance(command[field], str) or not command[field].strip():
                raise ValueError("Missing explicit value (use N/A when justified): " + field)
            if command[field].strip().casefold() in {"unknown", "todo", "tbd", "unverified", "review"}:
                raise ValueError("Unreviewed value: " + field)
        sources = {}
        for language in ("python", "csharp"):
            ids = command[language + "_candidate_ids"]
            if not isinstance(ids, list) or not all(isinstance(item, str) for item in ids) or len(set(ids)) != len(ids):
                raise ValueError("Invalid candidate reference list")
            if any(item not in index or index[item]["language"] != language for item in ids):
                raise ValueError("Unknown or wrong-language candidate reference")
            sources[language] = any(index[item]["scope"] == "source" for item in ids)
        if classification == "MATCH" and not all(sources.values()):
            raise ValueError("A match requires implementation evidence from both languages")
        if classification == "EXTENSION" and not sources["csharp"]:
            raise ValueError("A C# extension requires C# implementation evidence")
        if not any(sources.values()):
            raise ValueError("A reviewed entry requires a source candidate; tests alone are insufficient")
    return len(keys)


def resolve_review_sources(review, rows):
    index = {row["candidate_id"]: row for row in rows}
    return [dict(menu_id=command["menu_id"], state=command["state"], command_id=command["command_id"],
                 **{language: [{field: index[item][field] for field in ("candidate_id", "revision", "path", "line", "scope")}
                               for item in command[language + "_candidate_ids"]]
                    for language in ("python", "csharp")}) for command in review]


def coverage_report(review, rows, exclusions):
    """Account for candidates, not behavioral parity or heuristic completeness."""
    if not isinstance(exclusions, list):
        raise ValueError("Exclusions must be a JSON array")
    ids = {row["candidate_id"] for row in rows}
    if len(ids) != len(rows):
        raise ValueError("Duplicate inventory candidate identity")
    mapped = {item for command in review for language in ("python", "csharp")
              for item in command[language + "_candidate_ids"]}
    if not mapped <= ids:
        raise ValueError("Unknown mapped candidate")
    excluded = set()
    for entry in exclusions:
        if not isinstance(entry, dict) or set(entry) != {"candidate_id", "reason"}:
            raise ValueError("Invalid candidate exclusion fields")
        item, reason = entry["candidate_id"], entry["reason"]
        if not isinstance(item, str) or item not in ids or item in excluded or item in mapped:
            raise ValueError("Unknown, repeated or mapped exclusion candidate")
        if not isinstance(reason, str) or not reason.strip() or reason.strip().casefold() in {
            "unknown", "todo", "tbd", "unverified", "review", "n/a"
        }:
            raise ValueError("Candidate exclusion requires a specific reason")
        excluded.add(item)
    missing = sorted(ids - mapped - excluded)
    return dict(total=len(ids), mapped=len(mapped), excluded=len(excluded),
                remaining=len(missing), unreviewed_candidate_ids=missing,
                complete=not missing)


def write_csv(path, rows):
    # Prefix potential spreadsheet formulas in source snippets. JSON retains
    # exact source text. Excel must not execute a source line when opened.
    with path.open("x", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS)
        writer.writeheader()
        for row in rows:
            safe = {key: ("'" + value if isinstance(value, str) and value.startswith(("=", "+", "-", "@", "\t", "\r")) else value)
                    for key, value in row.items()}
            writer.writerow(safe)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csharp", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--csharp-ref", default="HEAD")
    parser.add_argument("--python", type=Path, required=True)
    parser.add_argument("--python-ref", default="HEAD")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--review", type=Path, help="Optional reviewed JSON array using review-fields.json")
    parser.add_argument("--exclusions", type=Path, help="Reviewed candidate exclusions JSON array")
    parser.add_argument("--require-complete", action="store_true", help="Reject any unaccounted candidate")
    args = parser.parse_args()
    cs = snapshot(args.csharp, args.csharp_ref, {"cs", "xaml"})
    py = snapshot(args.python, args.python_ref, {"py"})
    rows = cs.pop("candidates") + py.pop("candidates")
    review = json.loads(args.review.read_text(encoding="utf-8-sig")) if args.review else []
    if not isinstance(review, list):
        raise ValueError("Review must be a JSON array")
    reviewed = validate_review(review, rows)
    exclusions = json.loads(args.exclusions.read_text(encoding="utf-8-sig")) if args.exclusions else []
    coverage = coverage_report(review, rows, exclusions)
    if args.require_complete and not coverage["complete"]:
        parser.error(f"{coverage['remaining']} candidates still unreviewed; no output written")
    # Never overwrite previously witnessed results.
    args.out.mkdir(parents=True, exist_ok=False)
    write_csv(args.out / "candidates.csv", rows)
    result = dict(status="REVIEW_REQUIRED", csharp=cs, python=py, candidates=rows,
                  reviewed_commands=review, reviewed_count=reviewed,
                  reviewed_sources=resolve_review_sources(review, rows),
                  candidate_exclusions=exclusions, coverage=coverage)
    (args.out / "manifest.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.out / "review-fields.json").write_text(json.dumps(REVIEW_FIELDS, indent=2) + "\n", encoding="utf-8")
    (args.out / "review-template.json").write_text("[]\n", encoding="utf-8")
    (args.out / "exclusions-template.json").write_text("[]\n", encoding="utf-8")
    print(f"Candidates: {len(rows)}, reviewed commands: {reviewed}, "
          f"unaccounted candidates: {coverage['remaining']}; no acceptance claimed.")

if __name__ == "__main__":
    main()
