"""Read-only inventory of tracked C#/XAML sources. Python 3.10+, Git."""
import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

LIMITS = (500, 1000, 1500, 2000, 4000)
BANDS = ('<=500', '501-1000', '1001-1500', '1501-2000', '2001-4000', '>4000')
EXCLUDED_DIRS = {'bin', 'obj', 'vendor', 'generated', 'third_party', 'thirdparty'}
GENERATED_SUFFIXES = ('.g.cs', '.g.i.cs', '.generated.cs', '.designer.cs')
NAMESPACE = re.compile(r'^\s*namespace\s+([\w.]+)\s*[;{]', re.M)
PARTIAL = re.compile(r'^\s*(?:(?:public|internal|private|protected|static|abstract|sealed|readonly|ref|unsafe|partial)\s+)*partial\s+(?:class|struct|interface|record(?:\s+(?:class|struct))?)\s+([A-Za-z_]\w*(?:\s*<[^>{\n]+>)?)', re.M)


def git(root, *args, data=None):
    return subprocess.run(['git', '-C', str(root), *args], input=data,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True).stdout


def exclusion(path):
    p = PurePosixPath(path)
    if p.suffix.lower() not in ('.cs', '.xaml'):
        return 'not C#/XAML'
    if any(part.lower() in EXCLUDED_DIRS for part in p.parts[:-1]):
        return 'generated/vendor/build directory'
    if p.name.lower().endswith(GENERATED_SUFFIXES):
        return 'generated filename'
    return None


def band(lines):
    return BANDS[sum(lines > limit for limit in LIMITS)]


def physical_lines(text):
    return len(text.splitlines())


def partial_keys(text):
    # Heuristic, not a C# parser: files with several namespaces are ambiguous.
    namespaces = set(NAMESPACE.findall(text))
    if len(namespaces) > 1:
        return []
    ns = next(iter(namespaces), '<global>')
    return sorted({ns + '.' + re.sub(r'\s+', '', name) for name in PARTIAL.findall(text)})


def read_blobs(root, blobs):
    if not blobs:
        return {}
    raw = git(root, 'cat-file', '--batch', data=('\n'.join(blobs) + '\n').encode('ascii'))
    offset = 0
    result = {}
    for sha in blobs:
        end = raw.index(b'\n', offset)
        oid, kind, size = raw[offset:end].split()
        if kind != b'blob' or oid.decode() != sha:
            raise ValueError('Unexpected git object: ' + sha)
        start = end + 1
        stop = start + int(size)
        if raw[stop:stop + 1] != b'\n':
            raise ValueError('Invalid git batch framing')
        result[sha] = raw[start:stop]
        offset = stop + 1
    return result


def inventory(root, revision):
    sha = git(root, 'rev-parse', '--verify', revision + '^{commit}').decode().strip()
    tracked = git(root, 'ls-tree', '-r', '-z', sha).split(b'\0')
    files, excluded = {}, {}
    for entry in tracked:
        if not entry:
            continue
        meta, name = entry.split(b'\t', 1)
        mode, kind, oid = meta.decode().split()
        path = name.decode('utf-8')
        reason = exclusion(path)
        if reason == 'not C#/XAML':
            continue
        if reason or kind != 'blob' or mode == '120000':
            excluded[path] = reason or 'nonregular git entry'
        else:
            files[path] = oid
    blobs = read_blobs(root, sorted(set(files.values())))
    rows = {}
    for path, oid in sorted(files.items()):
        text = blobs[oid].decode('utf-8-sig')
        if re.search(r'<auto-generated\b', text[:2048], re.I):
            excluded[path] = 'auto-generated header'
            continue
        lines = physical_lines(text)
        rows[path] = {'lines': lines, 'band': band(lines),
                      'partial': partial_keys(text) if path.endswith('.cs') else []}
    groups = defaultdict(list)
    for path, row in rows.items():
        for key in row['partial']:
            # Keep assemblies/projects separate using the nearest project directory.
            # Here the repository layout is src/<project>, tests/<project>, etc.
            parts = PurePosixPath(path).parts
            scope = '/'.join(parts[:2]) if len(parts) > 2 else '.'
            groups[scope + ':' + key].append(path)
    partials = [{'type': key, 'files': paths, 'lines': sum(rows[p]['lines'] for p in paths)}
                for key, paths in groups.items() if len(paths) > 1]
    partials.sort(key=lambda r: (-r['lines'], r['type']))
    return {'revision': sha, 'files': rows, 'excluded': excluded, 'partials': partials}


def growth(before, after):
    changes = []
    for path, row in after.items():
        old = before.get(path, {}).get('lines', 0)
        new = row['lines']
        if new > old and (new > 4000 or new > 1000):
            changes.append({'path': path, 'before': old, 'after': new, 'delta': new - old,
                            'reason': '>4000 lines' if new > 4000 else 'large file grew'})
    return sorted(changes, key=lambda r: (-r['delta'], r['path']))


def report(data, baseline=None):
    print('Revision:', data['revision'])
    for scope in ('src', 'tests', 'other'):
        rows = {p: r for p, r in data['files'].items()
                if (p.split('/')[0] if p.split('/')[0] in ('src', 'tests') else 'other') == scope}
        counts = Counter(r['band'] for r in rows.values())
        print(f'{scope}: {len(rows)} files, {sum(r["lines"] for r in rows.values())} lines; ' +
              ', '.join(f'{b}: {counts[b]}' for b in BANDS))
    print('\nTop 30 files:')
    for path, row in sorted(data['files'].items(), key=lambda pair: (-pair[1]['lines'], pair[0]))[:30]:
        print(f'{row["lines"]:6}  {path}')
    print('\nPartial groups (approximate whole-file totals, not syntax-aware):')
    for row in data['partials'][:30]:
        print(f'{row["lines"]:6}  {row["type"]} ({len(row["files"])} files)')
    print('\nExcluded C#/XAML files:', len(data['excluded']))
    for path, reason in sorted(data['excluded'].items()):
        print(f'  {path}: {reason}')
    if baseline is not None:
        warnings = growth(baseline['files'], data['files'])
        print(f'\nGrowth warnings against {baseline["revision"]}: {len(warnings)} (nonblocking)')
        for row in warnings:
            print(f'  {row["path"]}: {row["before"]} -> {row["after"]} (+{row["delta"]}); {row["reason"]}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', default='.')
    parser.add_argument('--ref', default='HEAD', help='Committed snapshot, not working tree')
    parser.add_argument('--base', help='Optional committed baseline for growth warnings')
    parser.add_argument('--json', type=Path, help='Optional report output path')
    args = parser.parse_args()
    data = inventory(args.repo, args.ref)
    baseline = inventory(args.repo, args.base) if args.base else None
    report(data, baseline)
    if args.json:
        data['baseline'] = baseline['revision'] if baseline else None
        data['warnings'] = growth(baseline['files'], data['files']) if baseline else []
        args.json.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
