using System.Xml.Linq;
using GmcSmeta.Core.Domain;

namespace GmcSmeta.Core.Tests;

/// <summary>Source-level coverage guard. Runtime and physical mouse acceptance
/// are separate checks; new XAML tables must not silently miss a layout route.</summary>
public sealed class ColumnMenuCoverageTests
{
    [Fact]
    public void EveryDeclaredDataGridHasUniqueProfileOrExplicitSpecialRoute()
    {
        DirectoryInfo? root = new(AppContext.BaseDirectory);
        while (root is not null && !File.Exists(Path.Combine(root.FullName, "src", "GmcSmeta.App", "App.xaml")))
            root = root.Parent;
        Assert.NotNull(root);
        var app = Path.Combine(root!.FullName, "src", "GmcSmeta.App");
        XNamespace presentation = "http://schemas.microsoft.com/winfx/2006/xaml/presentation";
        XNamespace xaml = "http://schemas.microsoft.com/winfx/2006/xaml";
        XNamespace local = "clr-namespace:GmcSmeta.App";
        var profiles = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var specials = new HashSet<string>(StringComparer.Ordinal);
        var missing = new List<string>();
        foreach (var file in Directory.EnumerateFiles(app, "*.xaml", SearchOption.AllDirectories)
                     .Where(f => !Path.GetRelativePath(app, f).Split(Path.DirectorySeparatorChar)
                         .Any(p => p is "obj" or "bin")))
        {
            foreach (var grid in XDocument.Load(file).Descendants(presentation + "DataGrid"))
            {
                var name = (string?)grid.Attribute(xaml + "Name") ?? "(unnamed)";
                var key = (string?)grid.Attribute(local + "TableColumnMenu.Key");
                var location = Path.GetFileName(file) + ":" + name;
                if (!string.IsNullOrWhiteSpace(key))
                {
                    if (!ColumnLayoutKeyPolicy.IsValid(key)) missing.Add(location + ": invalid profile " + key);
                    if (!profiles.Add(key)) missing.Add(location + ": duplicate profile " + key);
                }
                else if (location is "EstimateView.xaml:EstimateGrid" or "StagesDialog.xaml:StagesGrid")
                    specials.Add(location);
                else missing.Add(location + ": no column menu route");
            }
        }
        Assert.Empty(missing);
        Assert.Equal(2, specials.Count);
        Assert.NotEmpty(profiles);
        Assert.Contains("TableColumnMenu.InstallHeaderMenu(EstimateGrid", File.ReadAllText(Path.Combine(app, "EstimateView.xaml.cs")));
        Assert.Contains("TableColumnMenu.AppendDynamicMenu(StagesGrid, StageMenu)", File.ReadAllText(Path.Combine(app, "StagesDialog.xaml.cs")));
    }

    [Theory]
    [InlineData("agreement.sources", true)]
    [InlineData("stage-distribution-42", true)]
    [InlineData("estimate_summary", true)]
    [InlineData("a.b.c", true)]
    [InlineData("../other", false)]
    [InlineData("a..b", false)]
    [InlineData(".a", false)]
    [InlineData("a.", false)]
    [InlineData("a/b", false)]
    [InlineData("a\\b", false)]
    [InlineData("C:drive", false)]
    [InlineData("", false)]
    public void ProfileKeyAcceptsNamespacedKeysButRejectsPathSyntax(string key, bool expected) =>
        Assert.Equal(expected, ColumnLayoutKeyPolicy.IsValid(key));

    [Fact]
    public void CachedGridReloadsLatestProfileWithoutRecapturingDefaults()
    {
        DirectoryInfo? root = new(AppContext.BaseDirectory);
        while (root is not null && !File.Exists(Path.Combine(root.FullName, "src", "GmcSmeta.App", "TableColumnMenu.cs")))
            root = root.Parent;
        Assert.NotNull(root);
        var code = File.ReadAllText(Path.Combine(root!.FullName, "src", "GmcSmeta.App", "TableColumnMenu.cs"));
        Assert.Contains("grid.Loaded += (_, _) => layout.OnLoaded();", code);
        Assert.Contains("ApplyProfile(Read(), restoreDefaults: true);", code);
        Assert.Contains("entry.Column.Width = entry.Width;", code);
        Assert.Contains("ApplyOrder(latest.Order);", code);
        Assert.Contains("generation == _profileGeneration", code);
        Assert.Contains("_entries.Where(x => !x.Excluded)", code);
        Assert.Contains("if (!Current() || entry.Protected", code);
    }

    [Fact]
    public void ProgrammaticallyCreatedTablesHaveExplicitColumnLayoutRoutes()
    {
        DirectoryInfo? root = new(AppContext.BaseDirectory);
        while (root is not null && !File.Exists(Path.Combine(root.FullName, "src", "GmcSmeta.App", "App.xaml")))
            root = root.Parent;
        Assert.NotNull(root);
        var app = Path.Combine(root!.FullName, "src", "GmcSmeta.App");
        // New programmatically created grids must be reviewed as well as XAML.
        // Match direct or target-typed creation and the shared factory.
        var routes = new Dictionary<string, string[]>(StringComparer.Ordinal)
        {
            ["PtoVorWindow.cs"] = ["EnableAutoGenerated(_preview,"],
            ["MetalDialogs.cs"] = ["SetKey(grid,"],
            ["CatalogPickerWindow.cs"] = ["SetKey(_items,"],
            ["PtoCertificatesWindow.cs"] = ["SetKey(_grid,"],
            ["ActSectionAmountsDialog.cs"] = ["SetKey(_grid,"],
            ["EstimateView.SpecUpdate.cs"] = ["SetKey(grid,", "SetKey(table,"],
            ["ProcurementRequestDialog.cs"] = ["SetKey(_grid,"],
            ["AttachmentWindow.cs"] = ["SetKey(_grid,"],
            ["ProcurementMovementDialog.cs"] = ["SetKey(_grid,"],
            ["PeopleImportPreviewWindow.cs"] = ["EnableAutoGenerated(_people,", "EnableAutoGenerated(_cars,"],
            ["ProcurementShopOrderPreview.cs"] = ["SetKey(_grid,"],
            ["ExcelImportPreviewWindow.cs"] = ["SetKey(_table,"],
            ["WorkspaceQueryWindows.cs"] = ["SetKey(_items,", "SetKey(_history,"],
            ["MetalRegisterWindow.cs"] = ["RefreshDynamic(_table,"],
            ["ExcelExistingUpdatePreviewWindow.cs"] = ["SetKey(_grid,"]
        };
        var constructor = new System.Text.RegularExpressions.Regex(
            @"\bnew\s+DataGrid\b\s*(?:\(|\{|\r?\n)|\bDataGrid\s+\w+\s*=\s*(?:new\s*\(|WorkspaceWindowUi\.Table\s*\()",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant);
        var found = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in Directory.EnumerateFiles(app, "*.cs", SearchOption.AllDirectories)
                     .Where(f => !Path.GetRelativePath(app, f).Split(Path.DirectorySeparatorChar)
                         .Any(p => p is "obj" or "bin")))
        {
            var code = File.ReadAllText(file);
            if (!constructor.IsMatch(code)) continue;
            var name = Path.GetFileName(file);
            Assert.True(routes.TryGetValue(name, out var markers), "Unreviewed programmatic DataGrid: " + name);
            found.Add(name);
            foreach (var marker in markers!)
                Assert.Contains("TableColumnMenu." + marker, code);
        }
        Assert.Equal(routes.Keys.Order(), found.Order());
    }
}
